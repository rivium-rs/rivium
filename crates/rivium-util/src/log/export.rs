use super::{
    ExportSettings,
    files::{self, Directory},
};
use rivium::{Error, Result};
use std::{
    fs::{self, File, OpenOptions},
    io::{self, Read, Seek, SeekFrom, Write},
    path::PathBuf,
    sync::{
        Arc, Condvar, Mutex,
        atomic::{AtomicU64, Ordering},
    },
    time::{Instant, SystemTime},
};

/// Monotonically allocated identifier within one process.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct ExportId(pub u64);

/// Date interval and optional subset of configured sink names.
#[derive(Clone, Debug)]
pub struct ExportRequest {
    /// First inclusive calendar date, `YYYY-MM-DD`.
    pub from: String,
    /// Last inclusive calendar date, `YYYY-MM-DD`.
    pub to: String,
    /// Empty selects all configured sinks.
    pub sinks: Vec<String>,
}

/// Ready archive metadata. The file is removed on cancellation or expiry.
#[derive(Clone, Debug)]
pub struct Archive {
    /// Local archive path; applications own download authorization.
    pub path: PathBuf,
    /// Actual archive size in bytes.
    pub size: u64,
    /// Safe generated basename.
    pub file_name: String,
}

/// Observable lifecycle of the sole export job.
#[derive(Clone, Debug)]
pub enum ExportState {
    /// Packing is in progress.
    Running,
    /// Complete and available until cancellation, expiry, or logger close.
    Ready(Archive),
    /// Cancellation was requested and observed.
    Cancelled,
    /// Packing or cleanup failed.
    Failed(String),
    /// The ready archive passed its retention deadline and was removed.
    Expired,
}

struct Job {
    id: ExportId,
    request: Option<ExportRequest>,
    state: ExportState,
    cancel: bool,
    expires: Option<Instant>,
}

struct State {
    job: Option<Job>,
    closed: bool,
    done: bool,
    failure: Option<String>,
}

struct Control {
    #[cfg(test)]
    release_gate: Mutex<Option<std::sync::mpsc::Receiver<()>>>,
    _thread: Mutex<Option<std::thread::JoinHandle<()>>>,
    state: Mutex<State>,
    changed: Condvar,
    sinks: Vec<String>,
}

/// Bounded, single-job diagnostic archive controller.
#[derive(Clone)]
pub struct Exporter(Arc<Control>);

impl Exporter {
    pub(super) fn new(
        directory: Arc<Directory>,
        sinks: Vec<String>,
        settings: ExportSettings,
        input_limit: u64,
    ) -> Result<Self> {
        let output = directory.path.join("exports");
        if let Ok(metadata) = fs::symlink_metadata(&output)
            && (!metadata.is_dir() || metadata.file_type().is_symlink())
        {
            return Err(Error::invalid("export directory must be a real directory"));
        }
        fs::create_dir_all(&output).map_err(files::io_error)?;
        // The directory lease excludes previous generations. Remove only the
        // precisely named files generated by this exporter after a crash.
        for entry in fs::read_dir(&output).map_err(files::io_error)? {
            let entry = entry.map_err(files::io_error)?;
            if let Some(name) = entry.file_name().to_str()
                && name
                    .strip_prefix("logs-")
                    .and_then(|s| s.strip_suffix(".zip"))
                    .is_some_and(|s| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit()))
            {
                files::reject_symlink(&entry.path()).map_err(files::io_error)?;
                fs::remove_file(entry.path()).map_err(files::io_error)?;
            }
        }
        let control = Arc::new(Control {
            #[cfg(test)]
            release_gate: Mutex::new(None),
            _thread: Mutex::new(None),
            state: Mutex::new(State {
                job: None,
                closed: false,
                done: false,
                failure: None,
            }),
            changed: Condvar::new(),
            sinks,
        });
        let export = Self(Arc::clone(&control));
        let thread = std::thread::Builder::new()
            .name("rivium-export".into())
            .spawn(move || {
                let outcome = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                    run_export(&directory, &output, &control, settings, input_limit)
                }));
                if outcome.is_err() {
                    let path = {
                        let mut state = super::lock(&control.state);
                        state.closed = true;
                        state
                            .failure
                            .get_or_insert_with(|| "export worker panicked".into());
                        state.job.as_mut().map(|job| {
                            job.state = ExportState::Failed("export worker panicked".into());
                            output.join(format!("logs-{}.zip", job.id.0))
                        })
                    };
                    if let Some(path) = path {
                        let _ = remove_archive(&path);
                    }
                }
                drop(outcome);
                #[cfg(test)]
                if let Some(gate) = control.release_gate.lock().unwrap().take() {
                    let _ = gate.recv();
                }
                drop(directory);
                super::lock(&control.state).done = true;
                control.changed.notify_all();
            })
            .map_err(files::io_error)?;
        *export.0._thread.lock().unwrap_or_else(|e| e.into_inner()) = Some(thread);
        Ok(export)
    }

    #[cfg(test)]
    pub(super) fn hold_release(&self) -> std::sync::mpsc::Sender<()> {
        let (release, gate) = std::sync::mpsc::channel();
        *self.0.release_gate.lock().unwrap() = Some(gate);
        release
    }

    /// Configured sink names, including the main file.
    pub fn sinks(&self) -> Vec<String> {
        self.0.sinks.clone()
    }

    /// Start the only job; a running or retained ready job must first be cancelled.
    pub fn start(&self, request: ExportRequest) -> Result<ExportId> {
        if !files::valid_date(&request.from)
            || !files::valid_date(&request.to)
            || request.from > request.to
        {
            return Err(Error::invalid("invalid export date interval"));
        }
        if request.sinks.len() > self.0.sinks.len()
            || request
                .sinks
                .iter()
                .any(|sink| !self.0.sinks.contains(sink))
        {
            return Err(Error::invalid("unknown or excessive export sinks"));
        }
        let mut state = super::lock(&self.0.state);
        if state.closed {
            return Err(Error::new(
                rivium::error::kinds::CONFLICT,
                "exporter is closed",
            ));
        }
        if state
            .job
            .as_ref()
            .is_some_and(|j| matches!(j.state, ExportState::Running | ExportState::Ready(_)))
        {
            return Err(Error::new(
                rivium::error::kinds::CONFLICT,
                "an export is already active",
            ));
        }
        if state.failure.is_some() {
            return Err(Error::internal(
                "export cleanup previously failed; no further disk growth is allowed",
            ));
        }
        static NEXT: AtomicU64 = AtomicU64::new(1);
        let id = ExportId(NEXT.fetch_add(1, Ordering::Relaxed));
        state.job = Some(Job {
            id,
            request: Some(request),
            state: ExportState::Running,
            cancel: false,
            expires: None,
        });
        drop(state);
        self.0.changed.notify_all();
        Ok(id)
    }

    /// Inspect the current job. Old/replaced IDs return not found.
    pub fn progress(&self, id: ExportId) -> Result<ExportState> {
        super::lock(&self.0.state)
            .job
            .as_ref()
            .filter(|j| j.id == id)
            .map(|j| j.state.clone())
            .ok_or_else(|| Error::new(rivium::error::kinds::NOT_FOUND, "unknown export"))
    }

    /// Return metadata only when the archive is ready.
    pub fn archive(&self, id: ExportId) -> Result<Archive> {
        match self.progress(id)? {
            ExportState::Ready(archive) => Ok(archive),
            _ => Err(Error::new(
                rivium::error::kinds::CONFLICT,
                "export is not ready",
            )),
        }
    }

    /// Cancel a job. A ready archive is removed before this method returns;
    /// running jobs check cancellation between fixed-size read/write chunks.
    pub fn cancel(&self, id: ExportId) {
        let mut state = super::lock(&self.0.state);
        let ready = if let Some(job) = state.job.as_mut().filter(|j| j.id == id) {
            job.cancel = true;
            matches!(job.state, ExportState::Ready(_))
        } else {
            false
        };
        self.0.changed.notify_all();
        while ready
            && !state.done
            && state
                .job
                .as_ref()
                .is_some_and(|job| job.id == id && matches!(job.state, ExportState::Ready(_)))
        {
            state = self
                .0
                .changed
                .wait(state)
                .unwrap_or_else(|e| e.into_inner());
        }
    }

    /// Permanently close admission and signal cancellation without waiting.
    pub fn close(&self) {
        let mut state = super::lock(&self.0.state);
        state.closed = true;
        if let Some(job) = state.job.as_mut() {
            job.cancel = true;
        }
        drop(state);
        self.0.changed.notify_all();
    }

    pub(super) fn pending(&self) -> usize {
        usize::from(!super::lock(&self.0.state).done)
    }

    pub(super) fn wait_closed(&self, until: Instant) -> Result<()> {
        let mut state = super::lock(&self.0.state);
        while !state.done {
            let left = until.saturating_duration_since(Instant::now());
            if left.is_zero() {
                if let Some(message) = &state.failure {
                    return Err(Error::internal(message.clone()));
                }
                return Err(Error::new(
                    rivium::error::kinds::TIMEOUT,
                    "export worker deadline; resources are still owned",
                ));
            }
            (state, _) = self
                .0
                .changed
                .wait_timeout(state, left)
                .unwrap_or_else(|e| e.into_inner());
        }
        let result = state
            .failure
            .as_ref()
            .map_or(Ok(()), |e| Err(Error::internal(e.clone())));
        drop(state);
        if let Some(thread) = super::lock(&self.0._thread).take() {
            let _ = thread.join();
        }
        result
    }
}

enum Work {
    Pack(ExportId, ExportRequest),
    Remove(ExportId, PathBuf, bool),
    Exit,
}

fn run_export(
    directory: &Directory,
    output: &std::path::Path,
    control: &Control,
    settings: ExportSettings,
    input_limit: u64,
) {
    loop {
        let work = {
            let mut state = super::lock(&control.state);
            loop {
                let closed = state.closed;
                if let Some(job) = state.job.as_mut() {
                    if let ExportState::Ready(archive) = &job.state {
                        let expired = job.expires.is_some_and(|until| until <= Instant::now());
                        if expired || job.cancel || closed {
                            break Work::Remove(
                                job.id,
                                archive.path.clone(),
                                expired && !closed && !job.cancel,
                            );
                        }
                    }
                    if closed {
                        job.request = None;
                        if matches!(job.state, ExportState::Running) {
                            job.state = ExportState::Cancelled;
                        }
                    } else if let Some(request) = job.request.take() {
                        break Work::Pack(job.id, request);
                    }
                }
                if closed {
                    break Work::Exit;
                }
                let wait = state
                    .job
                    .as_ref()
                    .and_then(|j| j.expires)
                    .map(|until| until.saturating_duration_since(Instant::now()));
                if let Some(wait) = wait {
                    (state, _) = control
                        .changed
                        .wait_timeout(state, wait)
                        .unwrap_or_else(|e| e.into_inner());
                } else {
                    state = control
                        .changed
                        .wait(state)
                        .unwrap_or_else(|e| e.into_inner());
                }
            }
        };
        match work {
            Work::Exit => break,
            Work::Remove(id, path, expired) => {
                let result = remove_archive(&path);
                let mut state = super::lock(&control.state);
                if let Err(error) = &result {
                    state
                        .failure
                        .get_or_insert_with(|| format!("export cleanup failed: {error}"));
                }
                if let Some(job) = state.job.as_mut().filter(|job| job.id == id) {
                    job.expires = None;
                    job.state = match result {
                        Ok(()) if expired => ExportState::Expired,
                        Ok(()) => ExportState::Cancelled,
                        Err(e) => ExportState::Failed(format!("export cleanup failed: {e}")),
                    };
                }
                drop(state);
                control.changed.notify_all();
            }
            Work::Pack(id, request) => {
                let path = output.join(format!("logs-{}.zip", id.0));
                let result = pack(
                    directory,
                    control,
                    id,
                    &request,
                    &path,
                    settings.max_size,
                    input_limit,
                );
                let cancelled = cancelled(control, id).is_err();
                let cleanup = if cancelled || result.is_err() {
                    remove_archive(&path)
                } else {
                    Ok(())
                };
                let mut state = super::lock(&control.state);
                if let Err(error) = &cleanup {
                    state
                        .failure
                        .get_or_insert_with(|| format!("export cleanup failed: {error}"));
                }
                if let Some(job) = state.job.as_mut().filter(|job| job.id == id) {
                    job.expires = None;
                    job.state = match (result, cleanup) {
                        (_, Err(error)) => {
                            ExportState::Failed(format!("export cleanup failed: {error}"))
                        }
                        (Ok(size), Ok(())) if !cancelled => {
                            job.expires = Instant::now().checked_add(settings.expire_after);
                            ExportState::Ready(Archive {
                                path,
                                size,
                                file_name: format!("logs-{}.zip", id.0),
                            })
                        }
                        (Ok(_), Ok(())) => ExportState::Cancelled,
                        (Err(error), Ok(())) if error.kind() == io::ErrorKind::Interrupted => {
                            ExportState::Cancelled
                        }
                        (Err(error), Ok(())) => ExportState::Failed(error.to_string()),
                    };
                }
                drop(state);
                control.changed.notify_all();
            }
        }
    }
}

fn remove_archive(path: &std::path::Path) -> io::Result<()> {
    match fs::remove_file(path) {
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
        result => result,
    }
}

fn cancelled(control: &Control, id: ExportId) -> io::Result<()> {
    let state = super::lock(&control.state);
    if state.closed || state.job.as_ref().is_none_or(|j| j.id != id || j.cancel) {
        Err(io::Error::new(
            io::ErrorKind::Interrupted,
            "export cancelled",
        ))
    } else {
        Ok(())
    }
}

struct ZipOutput {
    file: File,
    position: u64,
    maximum: u64,
}

impl Write for ZipOutput {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        if self
            .position
            .checked_add(bytes.len() as u64)
            .is_none_or(|end| end > self.maximum)
        {
            return Err(io::Error::new(
                io::ErrorKind::FileTooLarge,
                "export exceeds reserved disk budget",
            ));
        }
        let written = self.file.write(bytes)?;
        self.position += written as u64;
        Ok(written)
    }

    fn flush(&mut self) -> io::Result<()> {
        self.file.flush()
    }
}

impl Seek for ZipOutput {
    fn seek(&mut self, offset: SeekFrom) -> io::Result<u64> {
        self.position = self.file.seek(offset)?;
        Ok(self.position)
    }
}

fn pack(
    directory: &Directory,
    control: &Control,
    id: ExportId,
    request: &ExportRequest,
    path: &PathBuf,
    max: u64,
    input_limit: u64,
) -> io::Result<u64> {
    cancelled(control, id)?;
    // Keep source files linked and immutable while packing: unlinking a file
    // still held by the exporter would hide its disk usage from the ledger.
    let _directory_guard = super::lock(&directory.io);
    cancelled(control, id)?;
    let inputs = {
        let entries = files::owned_files(&directory.path, &control.sinks)?;
        let mut total = 0_u64;
        let mut inputs = Vec::new();
        for (name, size) in entries {
            let Some((sink, archived_day)) = files::file_sink(&name, &control.sinks) else {
                continue;
            };
            if !request.sinks.is_empty() && !request.sinks.iter().any(|s| s == sink) {
                continue;
            }
            let file = File::open(directory.path.join(&name))?;
            let current_day = files::date(file.metadata()?.modified().unwrap_or(SystemTime::now()));
            let day = archived_day.unwrap_or(&current_day);
            if day < request.from.as_str() || day > request.to.as_str() {
                continue;
            }
            total = total
                .checked_add(size)
                .ok_or_else(|| io::Error::other("export input overflow"))?;
            if total > input_limit {
                return Err(io::Error::other(
                    "export input exceeds configured disk budget",
                ));
            }
            inputs.push((name, size));
        }
        inputs
    };
    let file = OpenOptions::new()
        .create_new(true)
        .read(true)
        .write(true)
        .open(path)?;
    let mut zip = zip::ZipWriter::new(ZipOutput {
        file,
        position: 0,
        maximum: max,
    });
    let options = zip::write::SimpleFileOptions::default()
        .compression_method(zip::CompressionMethod::Deflated);
    let mut buffer = [0_u8; 8192];
    for (name, size) in inputs {
        let file = File::open(directory.path.join(&name))?;
        cancelled(control, id)?;
        zip.start_file(name, options).map_err(io::Error::other)?;
        let mut reader = file.take(size);
        loop {
            cancelled(control, id)?;
            let n = reader.read(&mut buffer)?;
            if n == 0 {
                break;
            }
            zip.write_all(&buffer[..n])?;
        }
        if reader.limit() != 0 {
            return Err(io::Error::other("log input changed during export"));
        }
    }
    cancelled(control, id)?;
    let output = zip.finish().map_err(io::Error::other)?;
    output.file.sync_all()?;
    Ok(output.file.metadata()?.len())
}

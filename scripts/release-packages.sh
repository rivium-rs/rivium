#!/usr/bin/env bash
# Scan only the six packages produced for this candidate, before verification/publishing credentials.
set -euo pipefail
[ "$#" -ge 1 ] || exit 2
mode=$1; shift
case "$mode:$#" in scan:4 | verify:3) ;; *) echo 'usage: release-packages.sh scan <packages> <release> <denylist> <artifacts> | verify <packages> <release> <artifacts>' >&2; exit 2 ;; esac
packages=$(cd "$1" && pwd)
release=$(cd "$2" && pwd)
root=$(cd "$(dirname "$0")/.." && pwd)
if [ "$mode" = scan ]; then denylist=$3; destination=$4; else destination=$3; fi
mkdir -p "$destination"
artifacts=$(cd "$destination" && pwd)
fail() { echo "release packages: $*" >&2; exit 1; }
# Cargo's workspace packager stages upload payloads here (single-package Cargo used the parent).
# Accept only a known, unambiguous layout, never arbitrary archives elsewhere in target.
if [ -d "$packages/tmp-crate" ]; then
  for file in "$packages"/*.crate; do
    [ ! -e "$file" ] || cmp -s "$file" "$packages/tmp-crate/$(basename "$file")" \
      || fail 'ambiguous package output layout'
  done
  packages="$packages/tmp-crate"
fi
version=$(jq -er '.version | select(test("^(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)$"))' "$release/release.json")
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
printf '%s\n' rivium rivium-util rivium-host rivium-http rivium-jni rivium-test | LC_ALL=C sort > "$work/names"
for file in "$packages"/*.crate; do
  [ -s "$file" ] || fail 'no packages were generated'
  basename "$file"
done | LC_ALL=C sort > "$work/actual"
sed "s/$/-$version.crate/" "$work/names" > "$work/expected"
cmp -s "$work/expected" "$work/actual" || fail 'missing, extra or stale package archive'
if [ "$mode" = verify ]; then
  [ -s "$artifacts/SHA256SUMS" ] || fail 'missing checksum manifest'
  if grep -Ev '^[a-f0-9]{64}  (\./[a-z-]+-[0-9.]+\.crate|notes\.md|release\.json)$' "$artifacts/SHA256SUMS" >/dev/null; then
    fail 'invalid checksum manifest entry'
  fi
  { sed 's|^|./|' "$work/expected"; printf '%s\n' notes.md release.json; } | LC_ALL=C sort > "$work/hash-names"
  awk '{print $2}' "$artifacts/SHA256SUMS" | LC_ALL=C sort > "$work/hash-actual"
  cmp -s "$work/hash-names" "$work/hash-actual" || fail 'incomplete or extra checksum entries'
  (cd "$artifacts" && shasum -a 256 -c SHA256SUMS)
  cp "$release/notes.md" "$release/release.json" "$packages/"
  (cd "$packages" && shasum -a 256 -c "$artifacts/SHA256SUMS")
  echo 'release packages: regenerated bytes match the scanned and verified artifacts'
  exit 0
fi
[ ! -e "$artifacts/SHA256SUMS" ] || fail 'artifact directory was already used'
while IFS= read -r name; do
  archive="$name-$version.crate"
  tar -tzf "$packages/$archive" > "$work/list" || fail 'cannot list package'
  [ -s "$work/list" ] || fail 'empty archive'
  LC_ALL=C sort "$work/list" | uniq -d > "$work/duplicates"
  [ ! -s "$work/duplicates" ] || fail 'duplicate archive path could conceal package content'
  while IFS= read -r entry; do
    [[ "$entry" = "$name-$version/"* ]] || fail 'archive path is outside its package'
    case "$entry" in *'/../'* | *'/..' | *'/./'*) fail 'unsafe archive path' ;; esac
  done < "$work/list"
  tar -tvzf "$packages/$archive" > "$work/types" || fail 'cannot inspect package entries'
  if grep -Ev '^[-d]' "$work/types" >/dev/null; then fail 'package contains a link or special file'; fi
  mkdir "$work/$name"
  tar -xzf "$packages/$archive" -C "$work/$name"
  if [ ! -s "$work/$name/$name-$version/Cargo.toml" ] || [ ! -s "$work/$name/$name-$version/src/lib.rs" ]; then
    fail 'package is missing its manifest or library source'
  fi
  "$root/scripts/check-public.sh" "$denylist" --dir "$work/$name"
  cp "$packages/$archive" "$artifacts/$archive"
done < "$work/names"
mkdir "$work/notes"
cp "$release/notes.md" "$release/release.json" "$work/notes/"
"$root/scripts/check-public.sh" "$denylist" --dir "$work/notes"
cp "$work/notes/"* "$artifacts/"
(cd "$artifacts" && shasum -a 256 ./*.crate notes.md release.json > SHA256SUMS)
echo 'release packages: six archives and notes scanned; checksums recorded'
